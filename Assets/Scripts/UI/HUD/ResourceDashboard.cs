using System;
using UnityEngine;
using UnityEngine.UI;
using TMPro;
using Outpost.UI.Core;

namespace Outpost.UI.HUD
{
    /// <summary>
    /// Displays real-time outpost life support and utility telemetry across 8 primary metrics.
    /// Purely a presentation layer connected to Computer 1's real resource systems.
    /// Contains zero duplicate simulations.
    /// </summary>
    public class ResourceDashboard : MonoBehaviour, IResourceDisplay
    {
        [System.Serializable]
        public class ResourceWidget
        {
            public string ResourceName;
            public Slider MeterSlider;
            public Image FillImage;
            public TextMeshProUGUI ValueText;
            public TextMeshProUGUI StatusBadgeText;
            [TextArea(1, 3)] public string DefaultExplanation;
            public float CurrentValue;
            public float MaxValue = 100f;
            public ResourceState CurrentState = ResourceState.Nominal;
        }

        [Header("The 8 Core Outpost Resources")]
        [SerializeField] private ResourceWidget _oxygen = new ResourceWidget { ResourceName = "Oxygen", DefaultExplanation = "Oxygen is extracted from lunar water ice using solar electrolysis." };
        [SerializeField] private ResourceWidget _water = new ResourceWidget { ResourceName = "Water", DefaultExplanation = "Closed-loop recycled water supplies drinking reserves and greenhouse hydration." };
        [SerializeField] private ResourceWidget _food = new ResourceWidget { ResourceName = "Food", DefaultExplanation = "Fresh hydroponic vegetables supplemented with sealed nutrition rations." };
        [SerializeField] private ResourceWidget _electricity = new ResourceWidget { ResourceName = "Electricity", DefaultExplanation = "Live electrical power generated by the crater ridge photovoltaic solar array." };
        [SerializeField] private ResourceWidget _battery = new ResourceWidget { ResourceName = "Battery", DefaultExplanation = "Stores reserve power to run life support during shadowed periods." };
        [SerializeField] private ResourceWidget _crewHealth = new ResourceWidget { ResourceName = "Crew Health", DefaultExplanation = "Monitored by Medical Officer Daniel. Tracks heart rates, vitals, and oxygen saturation." };
        [SerializeField] private ResourceWidget _equipmentCondition = new ResourceWidget { ResourceName = "Equipment Condition", DefaultExplanation = "Structural and mechanical integrity of outpost modules, solar panels, and rovers." };
        [SerializeField] private ResourceWidget _spareParts = new ResourceWidget { ResourceName = "Spare Parts", DefaultExplanation = "Mechanical filters, thermal hoses, replacement conduits, and emergency seal tape." };

        [Header("State Colors (Ages 7–12 Accessible)")]
        [SerializeField] private Color _nominalColor = new Color(0.18f, 0.8f, 0.44f, 1f);  // Crisp Emerald
        [SerializeField] private Color _warningColor = new Color(0.96f, 0.72f, 0.15f, 1f); // Solar Amber
        [SerializeField] private Color _criticalColor = new Color(0.94f, 0.26f, 0.21f, 1f); // Emergency Red

        [Header("Educational Science Detail Modal")]
        [SerializeField] private GameObject _detailModalPanel;
        [SerializeField] private TextMeshProUGUI _modalTitleText;
        [SerializeField] private TextMeshProUGUI _modalStatusText;
        [SerializeField] private TextMeshProUGUI _modalExplanationText;
        [SerializeField] private Button _closeModalButton;

        private void Awake()
        {
            if (_detailModalPanel != null) _detailModalPanel.SetActive(false);
            if (_closeModalButton != null) _closeModalButton.onClick.AddListener(CloseDetailModal);
        }

        private void OnEnable()
        {
            // Subscribe to Computer 1 events
            UIEventBus.OnResourceSnapshotUpdated += UpdateAllResources;
            UIEventBus.OnOxygenDataChanged += (cur, max, exp) => UpdateOxygen(cur, max, exp);
            UIEventBus.OnWaterDataChanged += (cur, max, exp) => UpdateWater(cur, max, exp);
            UIEventBus.OnFoodDataChanged += (cur, max, exp) => UpdateFood(cur, max, exp);
            UIEventBus.OnElectricityDataChanged += (cur, max, exp) => UpdateElectricity(cur, max, exp);
            UIEventBus.OnBatteryDataChanged += (cur, max, exp) => UpdateBattery(cur, max, exp);
            UIEventBus.OnCrewHealthDataChanged += (pct, exp) => UpdateCrewHealth(pct, exp);
            UIEventBus.OnEquipmentConditionDataChanged += (pct, exp) => UpdateEquipmentCondition(pct, exp);
            UIEventBus.OnSparePartsDataChanged += (count, exp) => UpdateSpareParts(count, exp);
        }

        private void OnDisable()
        {
            UIEventBus.OnResourceSnapshotUpdated -= UpdateAllResources;
            UIEventBus.OnOxygenDataChanged -= (cur, max, exp) => UpdateOxygen(cur, max, exp);
            UIEventBus.OnWaterDataChanged -= (cur, max, exp) => UpdateWater(cur, max, exp);
            UIEventBus.OnFoodDataChanged -= (cur, max, exp) => UpdateFood(cur, max, exp);
            UIEventBus.OnElectricityDataChanged -= (cur, max, exp) => UpdateElectricity(cur, max, exp);
            UIEventBus.OnBatteryDataChanged -= (cur, max, exp) => UpdateBattery(cur, max, exp);
            UIEventBus.OnCrewHealthDataChanged -= (pct, exp) => UpdateCrewHealth(pct, exp);
            UIEventBus.OnEquipmentConditionDataChanged -= (pct, exp) => UpdateEquipmentCondition(pct, exp);
            UIEventBus.OnSparePartsDataChanged -= (count, exp) => UpdateSpareParts(count, exp);
        }

        public void UpdateAllResources(OutpostResourceSnapshot snapshot)
        {
            ApplyEntryToWidget(_oxygen, snapshot.Oxygen);
            ApplyEntryToWidget(_water, snapshot.Water);
            ApplyEntryToWidget(_food, snapshot.Food);
            ApplyEntryToWidget(_electricity, snapshot.Electricity);
            ApplyEntryToWidget(_battery, snapshot.Battery);
            ApplyEntryToWidget(_crewHealth, snapshot.CrewHealth);
            ApplyEntryToWidget(_equipmentCondition, snapshot.EquipmentCondition);
            ApplyEntryToWidget(_spareParts, snapshot.SpareParts);
        }

        public void UpdateOxygen(float current, float max, string explanation = "")
        {
            UpdateWidgetValues(_oxygen, current, max, "%", 30f, 15f, false, explanation);
        }

        public void UpdateWater(float current, float max, string explanation = "")
        {
            UpdateWidgetValues(_water, current, max, "L", 25f, 10f, false, explanation);
        }

        public void UpdateFood(float current, float max, string explanation = "")
        {
            UpdateWidgetValues(_food, current, max, "Rations", 20f, 10f, false, explanation);
        }

        public void UpdateElectricity(float currentKw, float maxKw, string explanation = "")
        {
            UpdateWidgetValues(_electricity, currentKw, maxKw, "kW", 20f, 10f, false, explanation);
        }

        public void UpdateBattery(float currentKwh, float maxKwh, string explanation = "")
        {
            UpdateWidgetValues(_battery, currentKwh, maxKwh, "kWh", 30f, 15f, false, explanation);
        }

        public void UpdateCrewHealth(float percentage, string explanation = "")
        {
            UpdateWidgetValues(_crewHealth, percentage, 100f, "%", 50f, 25f, false, explanation);
        }

        public void UpdateEquipmentCondition(float percentage, string explanation = "")
        {
            UpdateWidgetValues(_equipmentCondition, percentage, 100f, "%", 40f, 20f, false, explanation);
        }

        public void UpdateSpareParts(int count, string explanation = "")
        {
            UpdateWidgetValues(_spareParts, count, 20f, "Units", 4f, 2f, false, explanation);
        }

        private void ApplyEntryToWidget(ResourceWidget widget, ResourceEntry entry)
        {
            if (widget == null) return;
            string exp = string.IsNullOrEmpty(entry.SimpleExplanation) ? widget.DefaultExplanation : entry.SimpleExplanation;
            UpdateWidgetValues(widget, entry.CurrentValue, entry.MaxValue, entry.Unit, entry.WarningThreshold, entry.CriticalThreshold, entry.IsLowerBetter, exp);
        }

        private void UpdateWidgetValues(ResourceWidget widget, float current, float max, string unit, float warnThresh, float critThresh, bool lowerIsBetter, string explanation)
        {
            if (widget == null) return;

            widget.CurrentValue = current;
            widget.MaxValue = max;
            if (!string.IsNullOrEmpty(explanation)) widget.DefaultExplanation = explanation;

            float ratio = max > 0f ? Mathf.Clamp01(current / max) : 0f;

            // Determine nominal/warning/critical state
            if (lowerIsBetter)
            {
                if (current >= critThresh) widget.CurrentState = ResourceState.Critical;
                else if (current >= warnThresh) widget.CurrentState = ResourceState.Warning;
                else widget.CurrentState = ResourceState.Nominal;
            }
            else
            {
                if (current <= critThresh) widget.CurrentState = ResourceState.Critical;
                else if (current <= warnThresh) widget.CurrentState = ResourceState.Warning;
                else widget.CurrentState = ResourceState.Nominal;
            }

            // Update UI widgets
            if (widget.MeterSlider != null) widget.MeterSlider.value = ratio;

            Color stateColor = widget.CurrentState switch
            {
                ResourceState.Critical => _criticalColor,
                ResourceState.Warning => _warningColor,
                _ => _nominalColor
            };

            if (widget.FillImage != null) widget.FillImage.color = stateColor;

            if (widget.ValueText != null)
            {
                widget.ValueText.text = unit == "%"
                    ? $"{widget.ResourceName}: {Mathf.RoundToInt(current)}%"
                    : $"{widget.ResourceName}: {Mathf.RoundToInt(current)} / {Mathf.RoundToInt(max)} {unit}";
            }

            if (widget.StatusBadgeText != null)
            {
                widget.StatusBadgeText.text = widget.CurrentState.ToString().ToUpper();
                widget.StatusBadgeText.color = stateColor;
            }
        }

        public void OpenDetailModalForResource(string resourceName)
        {
            ResourceWidget target = resourceName.ToLower() switch
            {
                "oxygen" => _oxygen,
                "water" => _water,
                "food" => _food,
                "electricity" => _electricity,
                "battery" => _battery,
                "crew health" => _crewHealth,
                "equipment condition" => _equipmentCondition,
                "spare parts" => _spareParts,
                _ => null
            };

            if (target != null && _detailModalPanel != null)
            {
                _detailModalPanel.SetActive(true);
                if (_modalTitleText != null) _modalTitleText.text = $"{target.ResourceName} Telemetry";
                if (_modalStatusText != null)
                {
                    _modalStatusText.text = $"Status: {target.CurrentState.ToString().ToUpper()} ({Mathf.RoundToInt(target.CurrentValue)} / {Mathf.RoundToInt(target.MaxValue)})";
                    _modalStatusText.color = target.CurrentState switch
                    {
                        ResourceState.Critical => _criticalColor,
                        ResourceState.Warning => _warningColor,
                        _ => _nominalColor
                    };
                }
                if (_modalExplanationText != null)
                {
                    _modalExplanationText.text = $"<b>Lunar Science Guide:</b>\n{target.DefaultExplanation}";
                }
            }
        }

        public void CloseDetailModal()
        {
            if (_detailModalPanel != null) _detailModalPanel.SetActive(false);
        }
    }
}
